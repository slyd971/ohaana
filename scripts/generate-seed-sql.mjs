// Generates supabase/seed.sql from the static demo data in lib/data/seed.ts.
// Usage: node scripts/generate-seed-sql.mjs   (Node >= 22.6, type stripping)
// Every row is flagged is_demo = true so public.purge_demo_data() can remove it before launch.
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { PROVIDERS, SERVICES } = await import(join(root, 'lib/data/seed.ts'))

const uuid = (key) => {
  const h = createHash('sha1').update(`ohaana-demo:${key}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`
}
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`)
const num = (v) => (v === null || v === undefined ? 'null' : String(v))
const slugify = (t) =>
  String(t).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')

const CAT = {
  'cat-1': 'c01', 'cat-2': 'c02', 'cat-3': 'c03', 'cat-4': 'c04', 'cat-5': 'c05', 'cat-6': 'c06',
  'cat-7': 'c07', 'cat-8': 'c08', 'cat-9': 'c09', 'cat-10': 'c0a', 'cat-11': 'c0b', 'cat-12': 'c0c',
}
const catUuid = (id) => `00000000-0000-4000-8000-000000000${CAT[id]}`

const out = []
out.push(`-- GENERATED by scripts/generate-seed-sql.mjs from lib/data/seed.ts — do not edit by hand.
-- Demo data only: every row is flagged is_demo = true. Remove with: select public.purge_demo_data();
-- Reference data (categories, cancellation policies) lives in migration 006, not here.
`)

// 1. auth users (the handle_new_user trigger creates public.users + provider_profiles)
out.push('-- Providers (auth users, no password: they cannot sign in)')
for (const p of PROVIDERS) {
  const meta = {
    role: 'provider',
    full_name: p.user?.full_name ?? p.business_name,
    avatar_url: p.user?.avatar_url ?? null,
    business_name: p.business_name,
    locale: 'fr',
  }
  out.push(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
values ('00000000-0000-0000-0000-000000000000', ${q(uuid(p.user_id))}, 'authenticated', 'authenticated', ${q(`demo+${p.id}@ohaana.test`)}, '', now(), '{"provider":"email","providers":["email"]}'::jsonb, ${q(JSON.stringify(meta))}::jsonb, now(), now());`
  )
}
out.push(`\nupdate public.users set is_demo = true where email like 'demo+%@ohaana.test';\n`)

// 2. provider profiles (created by the trigger, completed here)
out.push('-- Provider profiles')
for (const p of PROVIDERS) {
  out.push(
    `update public.provider_profiles set
  business_name = ${q(p.business_name)}, bio = ${q(p.bio)}, bio_en = ${q(p.bio_en)},
  languages = ${arr(p.languages)}, certifications = ${arr(p.certifications)},
  island = ${q(p.island)}::public.island, phone = ${q(p.phone)}, whatsapp = ${q(p.whatsapp)},
  is_approved = true, avg_rating = ${num(p.avg_rating)}, review_count = ${num(p.review_count)}, is_demo = true
where user_id = ${q(uuid(p.user_id))};`
  )
}

// 3. services
const slugs = { fr: new Set(), en: new Set(), es: new Set() }
const slugOf = (lang, text, id) => {
  let s = slugify(text)
  if (slugs[lang].has(s)) s = `${s}-${slugify(id)}`
  slugs[lang].add(s)
  return s
}

out.push('\n-- Services')
for (const s of SERVICES) {
  out.push(
    `insert into public.services (
  id, provider_id, category_id, title_fr, title_en, title_es, description_fr, description_en, description_es,
  slug_fr, slug_en, slug_es, island, price_cents, price_unit, duration_min, capacity_min, capacity_max,
  address, latitude, longitude, is_active, is_featured, status, tags, avg_rating, review_count, booking_count,
  is_demo, created_at, updated_at
) values (
  ${q(uuid(s.id))}, (select id from public.provider_profiles where user_id = ${q(uuid(PROVIDERS.find((p) => p.id === s.provider_id).user_id))}),
  ${q(catUuid(s.category_id))}, ${q(s.title_fr)}, ${q(s.title_en)}, ${q(s.title_es ?? s.title_en)},
  ${q(s.description_fr)}, ${q(s.description_en)}, ${q(s.description_es ?? s.description_en)},
  ${q(slugOf('fr', s.title_fr, s.id))}, ${q(slugOf('en', s.title_en, s.id))}, ${q(slugOf('es', s.title_es ?? s.title_en, s.id))},
  ${q(s.island)}::public.island, ${num(s.price_cents)}, 'per_person', ${num(s.duration_min)}, ${num(s.capacity_min)}, ${num(s.capacity_max)},
  ${q(s.address)}, ${num(s.latitude)}, ${num(s.longitude)}, ${s.is_active}, ${s.is_featured}, 'published', ${arr(s.tags)},
  ${num(s.avg_rating)}, ${num(s.review_count)}, ${num(s.booking_count)}, true, ${q(s.created_at)}, ${q(s.updated_at)}
);`
  )
}

// 4. images
out.push('\n-- Service images')
for (const s of SERVICES) {
  for (const im of s.images ?? []) {
    out.push(
      `insert into public.service_images (id, service_id, url, alt_fr, alt_en, alt_es, sort_order, is_cover)
values (${q(uuid(im.id))}, ${q(uuid(s.id))}, ${q(im.url)}, ${q(im.alt_fr)}, ${q(im.alt_en)}, ${q(im.alt_en)}, ${num(im.sort_order)}, ${im.is_cover});`
    )
  }
}

// 5. availability for the next 90 days (regenerate by re-running supabase db reset)
out.push(`
-- Availability: next 90 days, same start times as the booking UI. Slot length = service duration.
insert into public.availability_slots (service_id, date, start_time, end_time)
select s.id, d::date, t, (t + make_interval(mins => coalesce(s.duration_min, 60)))::time
from public.services s
cross join generate_series(current_date + 1, current_date + 90, interval '1 day') d
cross join unnest(array['09:00','10:00','11:00','14:00','15:00','16:00','18:00','19:00','20:00']::time[]) t
where s.is_demo
  and extract(epoch from t) / 60 + coalesce(s.duration_min, 60) <= 1439;
`)

writeFileSync(join(root, 'supabase/seed.sql'), out.join('\n') + '\n')
console.log(`seed.sql: ${PROVIDERS.length} providers, ${SERVICES.length} services`)
